/// Catalog name and id stay searchable. Shipped display names are included too.
String formulaSearchBlob(String id, String catalogName) {
  final buffer = StringBuffer(catalogName)
    ..write(' ')
    ..write(id.replaceAll('_', ' '));
  for (final names in formulaNames.values) {
    final label = names[id];
    if (label != null) {
      buffer
        ..write(' ')
        ..write(label);
    }
  }
  return buffer.toString();
}
